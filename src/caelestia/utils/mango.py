"""MangoWM IPC through `mmsg`, the counterpart of `hypr.py` for the mango branch.

`mmsg get <query>` prints one JSON object on stdout and `mmsg dispatch <func>,<args>`
answers `{"success": bool}`. Monitors carry no refresh rate, so it comes from
`wlr-randr --json` when available.
"""

import json
import os
import shutil
import subprocess
from pathlib import Path
from typing import Any

from caelestia.utils.paths import atomic_write, config_dir

TIMEOUT: float = 5

# Mango option name -> Material palette key. Names as in mango's own config.conf
# (border_color, focus_color...); the older bordercolor spelling is no longer read.
COLOUR_OPTIONS: dict[str, str] = {
    "border_color": "outline",
    "focus_color": "primary",
    "maximized_screen_color": "secondary",
    "urgent_color": "error",
    "scratchpad_color": "tertiary",
    "global_color": "onSurfaceVariant",
    "overlay_color": "surfaceContainerHighest",
}

# Written apart from the user's config: mango.conf pulls it in with
# `source_optional = ./caelestia-colours.conf`.
colours_path: Path = config_dir / "mango/caelestia-colours.conf"


def running() -> bool:
    return bool(os.getenv("MANGO_INSTANCE_SIGNATURE")) and shutil.which("mmsg") is not None


def query(name: str) -> dict[str, Any]:
    try:
        out = subprocess.check_output(["mmsg", "get", name], text=True, stderr=subprocess.DEVNULL, timeout=TIMEOUT)
        data = json.loads(out)
    except (OSError, subprocess.SubprocessError, json.JSONDecodeError):
        return {}
    return data if isinstance(data, dict) else {}


def monitors() -> list[dict[str, Any]]:
    return query("all-monitors").get("monitors", [])


def clients() -> list[dict[str, Any]]:
    return query("all-clients").get("clients", [])


def focused_monitor() -> dict[str, Any] | None:
    mons = monitors()
    return next((m for m in mons if m.get("active")), mons[0] if mons else None)


def dispatch(func: str, *args: Any) -> bool:
    params = [str(a) for a in args]
    # mmsg splits on commas, so an argument holding one would be cut in two.
    if any("," in p for p in params):
        raise ValueError(f"mango dispatch argument contains a comma: {params}")
    try:
        out = subprocess.check_output(
            ["mmsg", "dispatch", ",".join([func, *params])], text=True, stderr=subprocess.DEVNULL, timeout=TIMEOUT
        )
        return bool(json.loads(out).get("success"))
    except (OSError, subprocess.SubprocessError, json.JSONDecodeError, AttributeError):
        return False


def refresh_rate(output: str) -> float | None:
    if not shutil.which("wlr-randr"):
        return None
    try:
        heads = json.loads(subprocess.check_output(["wlr-randr", "--json"], text=True, timeout=TIMEOUT))
    except (OSError, subprocess.SubprocessError, json.JSONDecodeError):
        return None
    head = next((h for h in heads if h.get("name") == output), None)
    mode = next((m for m in (head or {}).get("modes", []) if m.get("current")), None)
    return float(mode["refresh"]) if mode and mode.get("refresh") else None


def gen_colours(colours: dict[str, str]) -> str:
    lines = ["# Generated by caelestia; regenerated on every scheme change."]
    for option, key in COLOUR_OPTIONS.items():
        if key in colours:
            lines.append(f"{option}=0x{colours[key]}ff")
    return "\n".join(lines) + "\n"


def apply_colours(colours: dict[str, str]) -> None:
    conf = gen_colours(colours)
    # Same scheme, same file: skip the write and the compositor reload.
    if colours_path.is_file() and colours_path.read_text() == conf:
        return
    atomic_write(colours_path, conf)
    if running():
        dispatch("reload_config")
